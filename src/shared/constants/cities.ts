export const cityOptions: CityOption[] = pakistanCities.map(
  ([english, urdu]) => ({english, urdu, value: `${english} / ${urdu}`}),
);

export function getBilingualCityName(city: string): string {
  const normalizedCity = city.trim().toUpperCase();
  return (
    cityOptions.find(
      option =>
        option.english === normalizedCity || option.value === city.trim(),
    )?.value ?? city.trim()
  );
}
